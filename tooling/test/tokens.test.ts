import { describe, expect, test } from "bun:test";
import {
  contrastRatio,
  renderCss,
  renderTables,
  replaceTables,
  tokenProblems,
  type TokenSources,
} from "../scripts/tokens-lib.js";

// A small token set in the shape of packages/ui/tokens/*.tokens.json.
function sources(): TokenSources {
  return {
    palette: {
      color: {
        $type: "color",
        paper: { $value: "#fbf7f0", $description: "Warm paper" },
        ink: { $value: "#2b2622", $description: "Dark ink" },
        night: { $value: "#1c1a17", $description: "Night paper" },
        mist: { $value: "#f1ebe2", $description: "Light ink" },
      },
    },
    base: {
      space: {
        $type: "dimension",
        "1": { $value: { value: 4, unit: "px" }, $description: "Tight" },
      },
      font: {
        body: {
          $type: "fontFamily",
          $value: ["system-ui", "Noto Sans Arabic", "sans-serif"],
          $description: "All text",
        },
      },
      leading: { $type: "number", $value: 1.5, $description: "Line height" },
    },
    light: {
      color: {
        $type: "color",
        bg: { $value: "{color.paper}", $description: "Page background" },
        text: {
          $value: "{color.ink}",
          $description: "Text",
          $extensions: { "day.cookto.contrast": { on: ["color.bg"] } },
        },
      },
    },
    dark: {
      color: {
        $type: "color",
        bg: { $value: "{color.night}", $description: "Page background" },
        text: {
          $value: "{color.mist}",
          $description: "Text",
          $extensions: { "day.cookto.contrast": { on: ["color.bg"] } },
        },
      },
    },
  };
}

describe("contrastRatio", () => {
  test("follows WCAG 2: black on white is 21, a colour on itself is 1", () => {
    expect(contrastRatio("#000000", "#ffffff")).toBeCloseTo(21, 1);
    expect(contrastRatio("#ffffff", "#000000")).toBeCloseTo(21, 1);
    expect(contrastRatio("#6b6259", "#6b6259")).toBeCloseTo(1, 5);
    expect(contrastRatio("#777777", "#ffffff")).toBeCloseTo(4.48, 2);
  });
});

describe("tokenProblems", () => {
  test("a valid set has none", () => {
    expect(tokenProblems(sources())).toEqual([]);
  });

  test("light and dark must name the same tokens", () => {
    const s = sources();
    delete (s.dark as { color: Record<string, unknown> }).color.text;
    expect(tokenProblems(s).join("\n")).toContain("color.text");
  });

  test("a semantic colour must come from the palette, not a raw value", () => {
    const s = sources();
    (s.light as { color: { bg: { $value: string } } }).color.bg.$value =
      "#ffffff";
    expect(tokenProblems(s).join("\n")).toContain("color.bg");
  });

  test("an alias must name a palette colour that exists", () => {
    const s = sources();
    (s.light as { color: { bg: { $value: string } } }).color.bg.$value =
      "{color.nope}";
    expect(tokenProblems(s).join("\n")).toContain("{color.nope}");
  });

  test("text that is hard to read fails, naming the pair, the theme and the ratio", () => {
    const s = sources();
    (s.dark as { color: { text: { $value: string } } }).color.text.$value =
      "{color.ink}";
    const found = tokenProblems(s).join("\n");
    expect(found).toContain("color.text on color.bg");
    expect(found).toContain("dark");
    expect(found).toContain("4.5");
  });

  test("every token says what it is for", () => {
    const s = sources();
    delete (s.base as { leading: { $description?: string } }).leading
      .$description;
    expect(tokenProblems(s).join("\n")).toContain("leading");
  });
});

describe("renderCss", () => {
  test("writes the variables, light by default and dark for a dark system, and never the palette", () => {
    const css = renderCss(sources());
    expect(css).toContain("Generated by `bun run tokens`");
    expect(css).toContain("--space-1: 4px;");
    expect(css).toContain(
      '--font-body: system-ui, "Noto Sans Arabic", sans-serif;',
    );
    expect(css).toContain("--leading: 1.5;");
    expect(css).toMatch(/:root \{[^}]*--color-bg: #fbf7f0;/);
    expect(css).toMatch(
      /@media \(prefers-color-scheme: dark\) \{\s*:root \{[^}]*--color-bg: #1c1a17;/,
    );
    expect(css).not.toContain("--color-paper");
  });
});

describe("DESIGN.md tables", () => {
  test("replaces what's between a group's markers with its table", () => {
    const md = [
      "# Design",
      "<!-- tokens:color -->",
      "old",
      "<!-- /tokens:color -->",
      "<!-- tokens:space -->",
      "<!-- /tokens:space -->",
      "after",
    ].join("\n");
    const out = replaceTables(md, renderTables(sources()));
    expect(out).toContain(
      "| Page background | `var(--color-bg)` | #fbf7f0 | #1c1a17 |",
    );
    expect(out).toContain("| `var(--space-1)` | 4px | Tight |");
    expect(out).not.toContain("old");
    expect(out).toContain("after");
  });

  test("fails when DESIGN.md has lost a group's markers", () => {
    expect(() => replaceTables("# Design", renderTables(sources()))).toThrow(
      "tokens:color",
    );
  });
});
